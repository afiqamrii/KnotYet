import assert from 'node:assert/strict';
import { chromium } from 'playwright-core';
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
try {
 const page=await browser.newPage({viewport:{width:390,height:844},reducedMotion:'reduce'});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://localhost:5174');
 await page.getByRole('button',{name:'Start playing',exact:true}).click();
 await page.getByRole('button',{name:'Open your profile'}).click();
 await page.locator('.profile-dashboard').waitFor();
 await page.getByRole('button',{name:'Back to games'}).focus();
 await page.keyboard.press('Shift+Tab');
 assert.equal(await page.getByRole('button',{name:'Sign out',exact:true}).evaluate(e=>e===document.activeElement),true,'Tab wraps within the profile');
 await page.keyboard.press('Tab');
 assert.equal(await page.getByRole('button',{name:'Back to games'}).evaluate(e=>e===document.activeElement),true);
 await page.getByRole('button',{name:'Invite your person'}).click();
 await page.evaluate(()=>{Object.defineProperty(navigator.clipboard,'writeText',{configurable:true,value:async()=>{throw new Error('Denied');}});});
 await page.getByRole('button',{name:'Copy link',exact:true}).click();
 assert.match(await page.getByRole('alert').innerText(),/copy it manually/);
 assert.ok(await page.getByLabel('Your invite link').inputValue());
 await page.keyboard.press('Escape');
 await page.evaluate(()=>localStorage.setItem('jodohdeck_partner',JSON.stringify({name:'My Favourite Teammate',avatarId:'maple',relationshipType:'lover',code:'local-test-partner'})));
 await page.reload();
 await page.locator('.profile-dashboard').waitFor();
 assert.match(await page.locator('.profile-person').innerText(),/My Favourite Teammate/);
 assert.doesNotMatch(await page.locator('.profile-person').innerText(),/0 shared/,'No fabricated shared score for local partners');
 await page.locator('.profile-person').scrollIntoViewIfNeeded();
 await page.screenshot({path:'artifacts/profile-phone-partner.png'});
 await page.getByRole('button',{name:'Unlink',exact:true}).click();
 await page.getByRole('button',{name:'Cancel',exact:true}).click();
 assert.match(await page.locator('.profile-person').innerText(),/My Favourite Teammate/);
 await page.getByRole('button',{name:'Unlink',exact:true}).click();
 await page.getByRole('button',{name:'Unlink partner',exact:true}).click();
 await page.getByRole('button',{name:'Invite your person'}).waitFor();
 assert.equal(await page.evaluate(()=>localStorage.getItem('jodohdeck_partner')),null);
 await page.getByRole('button',{name:'Sign out',exact:true}).click();
 await page.getByRole('button',{name:'Sign out',exact:true}).click();
 await page.getByRole('button',{name:'Start playing',exact:true}).waitFor();
 assert.equal(await page.evaluate(()=>localStorage.getItem('knotyet_guest_active')),null);
 await page.getByRole('button',{name:'Start playing',exact:true}).click();
 await page.getByRole('button',{name:'Open your profile'}).click();
 await page.reload();
 await page.locator('.profile-dashboard').waitFor();
 assert.equal(await page.locator('.profile-player-pass h2').innerText(),'Guest Player','Fresh guest session restores its own profile');
 assert.deepEqual(errors,[]);
 console.log('Partner profile, unlink/cancel, clipboard fallback, keyboard trap, sign out, and fresh guest reload passed.');
}finally{await browser.close();}
